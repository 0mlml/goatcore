// Compiles each membership scope and its `converge:` value into the binary
// (docs/design/mesh-change-control.md §4.1: a scope is governed by warrant
// when its declaration directory `ops/warrant/membership/<scope>/` exists AND
// its `_scope.yaml` says `converge: enforce`; `converge: report` is an
// adoption draft).
//
// Same idea as `goat acl test` compiling the ACL declaration in with
// `include_str!`: a released binary run outside the repo still knows which
// scopes it must not write membership on directly. The runtime check in
// `cmd::warrant::is_governed` prefers the directory under the repo root when
// there is one, so a scope's converge changed after this binary was built is
// honoured when the command runs inside a current checkout.
//
// A scope directory with no readable `_scope.yaml` is compiled in with ""
// (unreadable → governed at runtime). So is a retired single file
// `<scope>.yaml`: the converger refuses that layout, and refusing live writes
// is the safe reading of a declaration it cannot use.
//
// A missing membership directory yields an empty list rather than a build
// failure: the sibling Dockerfiles that build other workspace members copy
// only what they need, and none of them builds goat-cli.

use std::path::Path;

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../ops/warrant/membership");
    // A directory path makes cargo rescan everything under it.
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut scopes: Vec<(String, String)> = Vec::new();
    if let Ok(rd) = std::fs::read_dir(&dir) {
        for e in rd.flatten() {
            let p = e.path();
            let Some(name) = p.file_name().and_then(|s| s.to_str()) else {
                continue;
            };
            if p.is_dir() {
                if is_scope_id(name) {
                    let scope_file = p.join("_scope.yaml");
                    println!("cargo:rerun-if-changed={}", scope_file.display());
                    let text = std::fs::read_to_string(&scope_file).unwrap_or_default();
                    scopes.push((name.to_string(), converge_of(&text)));
                }
            } else if let Some(stem) = name.strip_suffix(".yaml") {
                // Retired single-file layout: compiled in as unreadable.
                if is_scope_id(stem) && !scopes.iter().any(|(s, _)| s == stem) {
                    scopes.push((stem.to_string(), String::new()));
                }
            }
        }
    }
    scopes.sort();
    // A directory and a retired file for the same scope: the directory's value wins.
    scopes.dedup_by(|b, a| {
        if a.0 == b.0 {
            if a.1.is_empty() {
                a.1 = b.1.clone();
            }
            true
        } else {
            false
        }
    });

    let body = format!(
        "/// (scope, converge) for each membership scope directory at build time\n\
         /// (generated by build.rs from `<scope>/_scope.yaml`). converge is \"\"\n\
         /// when it could not be read.\n\
         pub const MEMBERSHIP_SCOPES: &[(&str, &str)] = &[{}];\n",
        scopes
            .iter()
            .map(|(s, c)| format!("({s:?}, {c:?})"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let out = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("governed_scopes.rs");
    std::fs::write(out, body).expect("write governed_scopes.rs");
}

/// Only kebab scope ids; anything else is not a scope.
fn is_scope_id(s: &str) -> bool {
    !s.is_empty()
        && s
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

/// The top-level `converge:` value of a `_scope.yaml`, or "" when there is
/// none. A line scan (no YAML parser in the build): the key at column 0, an
/// optional trailing comment, optional quotes.
fn converge_of(text: &str) -> String {
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("converge:") {
            let v = rest.split(" #").next().unwrap_or("").trim();
            let v = v.trim_matches('"').trim_matches('\'');
            if v == "report" || v == "enforce" {
                return v.to_string();
            }
            return String::new();
        }
    }
    String::new()
}
