#!/usr/bin/env bash
# gen-allowed-signers.sh — render the image-signing trust list from the operator
# roster, at run time.
#
# WHY THIS IS NOT A COMMITTED FILE. ops/ci/check-no-identity-spillage.sh refuses
# SSH public keys in committed files, and it caught the first version of this
# work doing exactly that. The keys already have one home —
# .envrc.local.d/40-dev-ca-operators.envrc, gitignored — so committing a second
# copy would both trip the guard and create a roster that drifts from the real
# one silently.
#
# Emits OpenSSH allowed_signers format: <principal> <keytype> <key>
# Consumed by:  ssh-keygen -Y verify -f <this> -I <principal> -n bootstrap-image
#
# NOT recipients.txt. That is the AGE roster for encrypting the bootstrap
# bundle and holds no ssh keys at all; pointing -Y verify at it can never
# succeed, which is the bug that left pull-image.sh's verify unexecutable.
set -euo pipefail

OUT="${1:-}"
[ -n "$OUT" ] || { echo "usage: $(basename "$0") <output-path>" >&2; exit 1; }

n=0
{
  echo "# GENERATED by gen-allowed-signers.sh — do not commit."
  echo "# Source: DEV_CA_SSH_* in .envrc.local.d/40-dev-ca-operators.envrc"
  for var in $(env | sed -n 's/^\(DEV_CA_SSH_[A-Z0-9_]*\)=.*/\1/p' | sort); do
    key="${!var:-}"
    [ -n "$key" ] || continue
    handle="$(echo "${var#DEV_CA_SSH_}" | tr 'A-Z_' 'a-z-')"
    # keep only keytype + key material; drop any trailing comment, which is
    # often a personal hostname and has no business in a trust list
    set -- $key
    printf 'goat-operator@%s %s %s\n' "$handle" "$1" "$2"
    n=$((n+1))
  done
} > "$OUT"
chmod 600 "$OUT"

n="$(grep -c '^goat-operator@' "$OUT" || true)"
[ "$n" -gt 0 ] || {
  echo "gen-allowed-signers: no DEV_CA_SSH_* in the environment." >&2
  echo "  direnv allow, or source .envrc.local.d/40-dev-ca-operators.envrc" >&2
  exit 2; }
echo "gen-allowed-signers: $n signer(s) -> $OUT" >&2
