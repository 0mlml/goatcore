#!/usr/bin/env python3
"""Render declared-topics.yml -> textfile/goat_declared_topic.prom.

The topic-level sibling of expected-vendors/generate.py.
The .prom is committed (so the rsync deploy carries it) AND regenerated by
this script — run it after editing the snapshot and commit both. node-exporter's
textfile collector exposes the result as:

    goat_declared_topic{vendor="<anchor>",key_pattern="<anchor>/<class>/*"} 1

Each declared topic is reduced to the first-two-segments `<anchor>/<class>/*`
form so it joins the audit-subscriber's bounded-cardinality
goat_audit_samples_total{vendor,key_pattern} (key_pattern_label() in
ops/zenoh-trial-peers/audit-subscriber/src/main.rs). Duplicate classes under an
anchor (several declared topics in the same class) collapse to one series.

No third-party deps (no PyYAML) — a tiny line parser for the controlled snapshot
shape (`anchor:` then `  - <anchor>/<class>/...`).
"""

import pathlib
import sys

HERE = pathlib.Path(__file__).parent
SNAPSHOT = HERE / "declared-topics.yml"
OUT = HERE / "textfile" / "goat_declared_topic.prom"


def parse_snapshot(text: str) -> dict[str, list[str]]:
    sections: dict[str, list[str]] = {}
    current: str | None = None
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].rstrip()  # strip inline comments
        if not line.strip():
            continue
        if not line.startswith((" ", "\t")) and line.rstrip().endswith(":"):
            current = line.strip()[:-1]
            sections[current] = []
        elif current is not None and line.strip().startswith("- "):
            sections[current].append(line.strip()[2:].strip())
    return sections


def key_pattern_label(key_expr: str) -> str:
    """Mirror the audit-subscriber's key_pattern_label(): reduce to the first
    two path segments + `/*` so the declared series joins the actuals."""
    segments = [s for s in key_expr.split("/")]
    if len(segments) <= 1:
        return key_expr
    return f"{segments[0]}/{segments[1]}/*"


def render(sections: dict[str, list[str]]) -> str:
    lines = [
        ("# HELP goat_declared_topic Declared topic-class for an onboarded anchor "
        "(<anchor>/<class>/* form). Source: declared-topics.yml. Do not edit by "
        "hand — run generate.py."),
        "# TYPE goat_declared_topic gauge",
    ]
    seen: set[tuple[str, str]] = set()
    for anchor, keys in sections.items():
        for key in keys:
            kp = key_pattern_label(key)
            pair = (anchor, kp)
            if pair in seen:
                continue
            seen.add(pair)
            lines.append(
                f'goat_declared_topic{{vendor="{anchor}",key_pattern="{kp}"}} 1'
            )
    return "\n".join(lines) + "\n"


def main() -> int:
    sections = parse_snapshot(SNAPSHOT.read_text())
    out = render(sections)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != out:
            print("goat_declared_topic.prom is stale — run generate.py and commit.",
                  file=sys.stderr)
            return 1
        print("goat_declared_topic.prom is up to date.")
        return 0
    OUT.write_text(out)
    print(f"wrote {OUT} ({out.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
