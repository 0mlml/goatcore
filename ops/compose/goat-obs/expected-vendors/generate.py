#!/usr/bin/env python3
"""Render expected-vendors.yml -> textfile/goat_expected_vendor.prom.

The .prom is committed (so the rsync deploy carries it) AND regenerated by
this script — run it after editing the manifest and commit both. node-exporter's
textfile collector exposes the result as:

    goat_expected_vendor{vendor="<prefix>",active="true|false"} 1

`active="true"`  → should be streaming now (silence = alert).
`active="false"` → allowed to produce but not silence-alarmed (operator/shared/dormant).

No third-party deps (no PyYAML) — a tiny line parser for the controlled manifest
shape (`section:` then `  - item  # comment`).
"""

import pathlib
import sys

HERE = pathlib.Path(__file__).parent
MANIFEST = HERE / "expected-vendors.yml"
OUT = HERE / "textfile" / "goat_expected_vendor.prom"


def parse_manifest(text: str) -> dict[str, list[str]]:
    sections: dict[str, list[str]] = {}
    current: str | None = None
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].rstrip()  # strip inline comments
        if not line.strip():
            continue
        if not line.startswith((" ", "\t")) and line.rstrip().endswith(":"):
            current = line.strip()[:-1]
            sections[current] = []
        elif current is not None and line.strip().startswith("- "):
            sections[current].append(line.strip()[2:].strip())
    return sections


def render(sections: dict[str, list[str]]) -> str:
    active = sections.get("active", [])
    allowed_only = [v for v in sections.get("allowed", []) if v not in active]
    lines = [
        ("# HELP goat_expected_vendor Declared-expected producer on the goat fabric "
        "(active=should be streaming now). Source: expected-vendors.yml. Do not edit "
        "by hand — run generate.py."),
        "# TYPE goat_expected_vendor gauge",
    ]
    for v in active:
        lines.append(f'goat_expected_vendor{{vendor="{v}",active="true"}} 1')
    for v in allowed_only:
        lines.append(f'goat_expected_vendor{{vendor="{v}",active="false"}} 1')
    return "\n".join(lines) + "\n"


def main() -> int:
    sections = parse_manifest(MANIFEST.read_text())
    out = render(sections)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != out:
            print("goat_expected_vendor.prom is stale — run generate.py and commit.",
                  file=sys.stderr)
            return 1
        print("goat_expected_vendor.prom is up to date.")
        return 0
    OUT.write_text(out)
    print(f"wrote {OUT} ({out.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
