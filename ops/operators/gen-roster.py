# --- ADR 1151: kind is derived, not required -------------------------------

# The legacy ADR 1077 sector values collapse into the ADR 1151 target set before
# the kind table is read: military / law-enforcement / intelligence /
# civil-government are all `state`; ngo / media / academic are all
# `civil-society`. Keeping the collapse here (rather than only in the console)
# is what makes a manifest derive the SAME kind on both sides of the language
# boundary — ops/goat-id-console/internal/coalition/derive.go is the sibling.
_SECTOR_TO_TARGET = {
    "state": "state",
    "military": "state",
    "law-enforcement": "state",
    "intelligence": "state",
    "civil-government": "state",
    "commercial": "commercial",
    "civil-society": "civil-society",
    "ngo": "civil-society",
    "media": "civil-society",
    "academic": "civil-society",
}


# ISO 3166-1 alpha-2 -> alpha-3, kept byte-identical with the two Go copies
# (ops/goat-id-console/internal/nation/nation.py-equivalent nation.go and
# ops/goat-zenoh-portal/internal/access/coalition.go) by
# ops/ci/check-nation-fold-parity.sh.
#
# WHY THIS EXISTS HERE. The operator-manifest schema calls alpha-3 "preferred"
# but its pattern is ^[A-Z]{2,8}$, so both spellings validate and a roster can
# carry either: US and USA, UK and ISL. derive_kind
# decides organic-vs-partner by comparing the org's nation to the goatnet's
# operating sovereign, and an unfolded comparison of US against USA answers
# "partner" — it reclassifies a nation's own units as foreign, which is exactly
# the bug ADR 1151 exists to fix.
_ALPHA2_TO_3 = {
    "AL": "ALB", "BE": "BEL", "BG": "BGR", "CA": "CAN", "HR": "HRV",  # oss-allow: public ISO or alliance table
    "CZ": "CZE", "DK": "DNK", "EE": "EST", "FI": "FIN", "FR": "FRA",  # oss-allow: public ISO or alliance table
    "DE": "DEU", "GR": "GRC", "HU": "HUN", "IS": "ISL", "IT": "ITA",  # oss-allow: public ISO or alliance table
    "LV": "LVA", "LT": "LTU", "LU": "LUX", "ME": "MNE", "NL": "NLD",  # oss-allow: public ISO or alliance table
    "MK": "MKD", "NO": "NOR", "PL": "POL", "PT": "PRT", "RO": "ROU",  # oss-allow: public ISO or alliance table
    "SK": "SVK", "SI": "SVN", "ES": "ESP", "SE": "SWE", "TR": "TUR",  # oss-allow: public ISO or alliance table
    "GB": "GBR", "UK": "GBR", "US": "USA", "UA": "UKR",  # oss-allow: public ISO or alliance table
}


def normalize_nation(n):
    """Upper-case, trim, and fold a known alpha-2 code to alpha-3.

    Anything that is not a known alpha-2 is returned unchanged, which is what
    keeps NATO and EU working: they are not countries and must pass through so
    the coalition frameworks' member markers still match them.
    """
    n = (n or "").strip().upper()
    return _ALPHA2_TO_3.get(n, n)


_ALPHA3 = re.compile(r"^[A-Z]{3}$")


def _member_nationality(ident: dict, warnings: list) -> str | None:
    """The person's own nationality as an alpha-3 code, or None (undeclared).

    A value that is still not alpha-3 after folding is not a nationality the
    roster can carry: `check-roster-registry.py` refuses it, and every consumer
    compares alpha-3 codes, so `BRITISH` would match nothing anyway. The console
    refuses such values at submit, but older manifests can carry free text. It
    is emitted as undeclared and named in a warning, so the manifest gets fixed
    instead of the roster failing CI or asserting a code nobody entered.
    """
    raw = ident.get("nationality")
    n = normalize_nation(raw)
    if not n:
        return None
    if not _ALPHA3.match(n):
        warnings.append(
            f"member '{ident.get('handle', '?')}': nationality {raw!r} is not an "
            f"ISO 3166-1 alpha-3 code — emitted as undeclared; fix identity.nationality "
            f"in the manifest"
        )
        return None
    return n


def derive_kind(sector, nation, operating_sovereign):
    """Derive the deprecated affiliation.kind from the ADR 1151 target block.

    Returns None when the inputs cannot decide, and a caller MUST then keep
    whatever the manifest carries rather than invent a value:

      - an unknown or absent sector; or
      - a `state` sector with no operating sovereign declared, because
        organic-vs-foreign is relative to the operator and has no answer without
        one. Defaulting it either way would silently reclassify a nation's own
        units, which is the bug ADR 1151 exists to fix.
    """
    target = _SECTOR_TO_TARGET.get((sector or "").strip().lower())
    if target == "commercial":
        return "vendor"
    if target == "civil-society":
        return "civil"
    if target != "state":
        return None
    n = normalize_nation(nation)
    s = normalize_nation(operating_sovereign)
    if not n or not s:
        return None
    return "organic" if n == s else "partner"


def _email_hash(email: str | None) -> str | None:
    """Sanitization-safe reconciliation key: SHA-256 of the lowercased email.

    The portal can't reconcile a live Ory identity (email) to a declared member
    when the person carries no vendor short-tag (organic/partner people don't) —
    it mis-flags them as strays and affiliation can't attach. This hash
    is a stable, non-human-readable matching key: the portal SHA-256s the Ory
    email and matches. No PII is added beyond what the kebab handles already
    reveal about who is enrolled; the join itself lives in Go, not here.
    """
    if not email:
        return None
    return hashlib.sha256(email.strip().lower().encode("utf-8")).hexdigest()

# Collaboration-environment projection states. A CLOSED vocabulary —
# ops/ci/check-roster-registry.py rejects anything outside it, and consumers may
# switch on it exhaustively.
COLLAB_UNRECORDED = "unrecorded"  # no usable collab block: NOTHING is known
COLLAB_NONE = "none"              # explicitly `enabled: false` — a recorded no
COLLAB_DECLARED = "declared"      # granted, but no account id recorded yet
COLLAB_ACCOUNT = "account"        # an account is recorded against this person
COLLAB_STATES = {COLLAB_UNRECORDED, COLLAB_NONE, COLLAB_DECLARED, COLLAB_ACCOUNT}


def _collab_projection(m: dict) -> dict:
    """Project the manifest's `collab` block to {state, provider}.

    The honesty rule this exists for: **absent is not none.** A manifest with no
    collab block tells you nothing about whether that person holds a
    collaboration-environment account — the account may well exist and simply
    never have been written down (F-274: 65 live accounts, zero manifests
    recording one). Rendering that as "no collab access" would manufacture a
    fact. So:

      unrecorded — no block, or a block that states no decision. UNKNOWN.
                   Reconcile against the provider (`onboard-runner -collab
                   reconcile`) to learn the truth; do not infer it from here.
      none       — `enabled: false`. Someone decided this person gets no collab.
      declared   — `enabled: true`, no `account`. Access granted; the account id
                   was never recorded (or the provider is opaque and exposes none).
      account    — an `account` id is recorded. The person has a collab account.

    Emits the provider SLUG (the service, e.g. `goat-collab`) but never the
    account id: the id is a login identifier on a partner-facing plane, and this
    file is the public-safe artifact. Presence + status + service only.
    """
    block = m.get("collab")
    if not isinstance(block, dict):
        return {"state": COLLAB_UNRECORDED, "provider": None}
    account = block.get("account")
    account = account.strip() if isinstance(account, str) else ""
    enabled = block.get("enabled")
    if account:
        state = COLLAB_ACCOUNT
    elif enabled is True:
        state = COLLAB_DECLARED
    elif enabled is False:
        state = COLLAB_NONE
    else:
        # A block that carries neither a decision nor an account states nothing
        # (the schema requires `enabled`, so this is a malformed/partial block).
        state = COLLAB_UNRECORDED
    provider = block.get("provider")
    return {
        "state": state,
        "provider": provider.strip() if isinstance(provider, str) and provider.strip() else None,
    }


# Subdirectories under ops/operators/ that are NOT per-env manifest folders.
_NON_ENV_SUBDIRS = {"out", "schema", "test-revoke"}


def _manifest_paths(base: Path, env: str | None = None) -> list[Path]:
    """The manifests one generation run may read.

    With ``env``: ONLY ``<base>/<env>/<handle>.yml``. That goatnet's own
    manifest folder is the whole population of its roster (ADR 1172) — the
    folder ``ops/scripts/sync-onboarded-manifests.py --env <env>`` fills from
    that goatnet's own console. The flat ``<base>/*.yml`` set is deliberately
    NOT included: those manifests predate the per-env layout and name no
    goatnet, so folding them in is exactly the union this split removes.

    Without ``env``: flat ``<base>/<handle>.yml`` plus one level of per-env
    subfolders — the controller-side union. Mirrors validate.py's gatherer.
    """
    if env:
        return sorted((base / env).glob("*.yml"))
    paths = list(base.glob("*.yml"))
    for sub in base.iterdir():
        if sub.is_dir() and sub.name not in _NON_ENV_SUBDIRS:
            paths += sub.glob("*.yml")
    return sorted(paths)


def load_manifests(base: Path, env: str | None = None) -> list[dict]:
    out = []
    for path in _manifest_paths(base, env):
        if path.name.endswith(".example"):
            continue
        try:
            doc = yaml.safe_load(path.read_text()) or {}
        except yaml.YAMLError as exc:
            print(f"WARN: skipping unparseable {path.name}: {exc}", file=sys.stderr)
            continue
        if isinstance(doc, dict) and doc.get("identity"):
            out.append(doc)
    return out


def build_registry(manifests: list[dict], operating_sovereign: str | None = None) -> dict:
    """Resolve the flat manifest set into the principal graph: orgs (with the
    affiliation block's kind/nation/parent) → members, plus a flat member list.
    Returns {"orgs": [...], "members": [...], "warnings": [...]}.

    operating_sovereign is the ISO-3166-1 alpha-3 nation running this goatnet
    (ADR 1151). It is needed ONLY to derive `kind` for a manifest that declares
    the target block and no kind, and only for a `state` sector. None (the
    default) means the organic question has no answer here, and such a manifest
    keeps whatever kind it carries rather than being assigned one — absent beats
    guessed.
    """
    # email -> handle, so custody (enrolled_by, an email) renders as a handle.
    # Only non-empty emails (systems have none; an empty key would mis-map).
    email_to_handle = {
        m["identity"]["email"].lower(): m["identity"].get("handle", "")
        for m in manifests
        if m["identity"].get("email")
    }

    orgs: dict[str, dict] = {}
    warnings: list[str] = []

    for m in manifests:
        ident = m["identity"]
        aff = m.get("affiliation") or {}
        # The legacy top-level block carries the org's short_tag + display_name.
        # ADR 1052 renames the block `vendor:` → `org:` (additive); read the
        # org-neutral key first, fall back to the legacy `vendor:` key. Same shape.
        vendor = m.get("org") or m.get("vendor") or {}

        # Grouping key: affiliation.id (the new hierarchical unit slug) wins;
        # legacy manifests fall back to the org/vendor short_tag, then no-org bucket.
        org_id = aff.get("id") or vendor.get("short_tag") or NO_ORG
        is_no_org = org_id == NO_ORG
        # Explicit affiliation.kind is authoritative; the legacy org/vendor block is
        # only a *fallback* (ADR 1043 migration: vendor block ⇒ kind vendor). An
        # explicit organic/partner must therefore beat a sibling's vendor
        # fallback, not collide with it. The heterogeneous no-org bucket carries
        # no affiliation attributes at all.
        explicit_kind = None if is_no_org else aff.get("kind")
        fallback_kind = None if is_no_org else ("vendor" if vendor else None)
        # ADR 1151: affiliation.kind is no longer REQUIRED in the manifest schema.
        # A manifest that declares only the target block (sector + gov_branch)
        # would otherwise land here with kind=None and the org would lose a fact
        # it actually states. Derive it — the same table the console derives, kept
        # in step with it by test_gen_roster_derive_kind.py.
        #
        # This is a FALLBACK, not an override: an explicit kind still wins, so a
        # manifest that carries both is unaffected and nothing changes meaning.
        if explicit_kind is None and not is_no_org:
            derived = derive_kind(aff.get("sector"), aff.get("nation"), operating_sovereign)
            if derived is not None:
                fallback_kind = derived
        # Folded to alpha-3 on the way into the projection so the roster carries
        # one spelling per country. Both spellings validate in the manifest
        # schema and both are in the tree, so an unfolded projection hands the
        # portal US and USA as two different countries — and reports the same
        # org's nation as "conflicting" when two members spell it differently.
        nation = None if is_no_org else (normalize_nation(aff.get("nation")) or None)
        parent = None if is_no_org else aff.get("parent")
        # unit_code: the codified unit-identity code (US UIC / NATO LOGFAS / SAP-ERP).
        # A MUTABLE registry attribute (ADR 1051) — the manifest seeds the current
        # value; carried into the roster as the current org-level code (effective-dated
        # history lives in the registry proper, not this generated snapshot).
        unit_code = None if is_no_org else aff.get("unit_code")
        # ADR 1112/1151: fields operators enter that the roster used to DROP.
        # sector (institutional sector), display_name (org label), alliance_standing
        # (dual-read the legacy `standing`/`coalition` keys, ADR 1151).
        sector = None if is_no_org else aff.get("sector")
        display_name = None if is_no_org else aff.get("display_name")
        alliance_standing = None if is_no_org else (aff.get("alliance_standing") or aff.get("standing") or aff.get("coalition"))

        org = orgs.get(org_id)
        if org is None:
            org = {
                "id": org_id,
                "kind": explicit_kind,
                "_fallback_kind": fallback_kind,
                "nation": nation,
                "parent": parent,
                "unit_code": unit_code,
                "sector": sector,
                "display_name": display_name,
                "alliance_standing": alliance_standing,
                "members": [],
            }
            orgs[org_id] = org
        else:
            # Explicit kind wins over fallback; warn only on explicit-vs-explicit
            # disagreement (a genuine manifest inconsistency to fix).
            if explicit_kind is not None:
                if org["kind"] is None:
                    org["kind"] = explicit_kind
                elif org["kind"] != explicit_kind:
                    warnings.append(
                        f"org '{org_id}': conflicting affiliation.kind "
                        f"('{org['kind']}' vs '{explicit_kind}' in {ident.get('handle', '?')}) — using first"
                    )
            if org["_fallback_kind"] is None and fallback_kind is not None:
                org["_fallback_kind"] = fallback_kind
            # nation / parent / unit_code come only from affiliation — any conflict is real.
            for attr, val in (("nation", nation), ("parent", parent), ("unit_code", unit_code), ("sector", sector), ("display_name", display_name), ("alliance_standing", alliance_standing)):
                if val is None:
                    continue
                if org[attr] is None:
                    org[attr] = val
                elif org[attr] != val:
                    warnings.append(
                        f"org '{org_id}': conflicting {attr} "
                        f"('{org[attr]}' vs '{val}' in {ident.get('handle', '?')}) — using first"
                    )

        enroller_email = (ident.get("enrolled_by") or "").lower()
        org["members"].append(
            {
                "handle": ident.get("handle", "?"),
                "type": ident.get("type", "person"),
                "state": ident.get("status", "?"),
                "added": str(ident.get("added", "?")),
                "custody": email_to_handle.get(
                    enroller_email, "—" if not enroller_email else "(external)"
                ),
                "autonomy": (ident.get("autonomy") or None),
                # The legacy per-identity vendor short-tag (distinct from the
                # org's affiliation.id). It is the key the portal's live Kratos
                # identities still carry (traits.vendor.short_tag) and reconcile
                # against until the Ory `aff` claim cutover (Phase D), so the
                # flat member list exposes it for declared-vs-actual matching.
                "vendor_tag": (vendor.get("short_tag") or None),
                # Sanitization-safe reconciliation key: matches a live
                # Ory identity by email hash even when it has no vendor tag
                # (organic/partner people), so they aren't mis-flagged as strays.
                "email_hash": _email_hash(ident.get("email")),
                # Collaboration-environment projection: the tracked view
                # of the manifest `collab` block. State + provider only — never
                # the account id. `unrecorded` means UNKNOWN, not "no account".
                "collab": _collab_projection(m),
                # ADR 1171: the PERSON's own citizenship, from identity.nationality.
                # Never taken from the org — a Canadian officer at a US command
                # is CAN, and the org is USA, and both are true. Absent means
                # UNDECLARED, which is a real state and must not be filled in
                # from the affiliation: doing that is the inference ADR 1171
                # exists to delete, and it would read as an assertion nobody made.
                "nationality": _member_nationality(ident, warnings),
            }
        )

    # Stable ordering: orgs alphabetical; members by state then handle.
    # Handles first: the org emit below needs to know whether an org id is also
    # somebody's handle.
    person_handles = {
        r["handle"] for o in orgs.values() for r in o["members"] if r.get("handle")
    }
    ordered_orgs = []
    flat_members = []
    for org_id in sorted(orgs):
        org = orgs[org_id]
        # Resolve final kind: explicit affiliation.kind wins, else the vendor
        # fallback, else unknown. Drop the internal scratch key.
        if org["kind"] is None:
            org["kind"] = org["_fallback_kind"]
        del org["_fallback_kind"]
        # Drop unit_code entirely when absent so roster.json stays clean.
        if org.get("unit_code") is None:
            org.pop("unit_code", None)
        # An org whose id is also a person's handle is that person's own
        # one-member org, and its display_name is then their name in title case.
        # The kebab id is already the roster's public-safe vocabulary; rendering
        # it back into "Firstname Lastname" adds no fact and puts a human name
        # into an artifact whose whole contract is that it carries none. Drop
        # the label, keep the id. The underlying data problem is a registry-tidy
        # question (ADR 1112 alias absorption),
        # not something this projection should paper over by inventing a name.
        if org.get("display_name") and org["id"] in person_handles:
            org.pop("display_name", None)
        for _opt in ("sector", "display_name", "alliance_standing", "composition"):
            if org.get(_opt) is None:
                org.pop(_opt, None)
        org["members"].sort(key=lambda r: (STATE_ORDER.get(r["state"], 9), r["handle"]))
        ordered_orgs.append(org)
        for r in org["members"]:
            flat_members.append(
                {
                    "handle": r["handle"],
                    "type": r["type"],
                    "org": org_id,
                    "vendor_tag": r["vendor_tag"],
                    "status": r["state"],
                    "email_hash": r["email_hash"],
                    "collab": r["collab"],
                    "nationality": r["nationality"],
                }
            )

    return {"orgs": ordered_orgs, "members": flat_members, "warnings": warnings}


def _collab_cell(collab: dict) -> str:
    """One table cell for the collab projection. `unrecorded` renders as `?`,
    NOT as a dash: a dash reads as "none" at a glance, and the whole point of the
    four-state vocabulary is that unknown must not look like a recorded no."""
    state = collab.get("state", COLLAB_UNRECORDED)
    if state == COLLAB_UNRECORDED:
        return "?"
    if state == COLLAB_ACCOUNT and collab.get("provider"):
        return f"account ({collab['provider']})"
    return state


def _aff_line(org: dict) -> str:
    """One sanitized affiliation-attributes line for an org section."""
    bits = []
    bits.append(f"kind: {org['kind']}" if org["kind"] else "kind: —")
    if org["nation"]:
        bits.append(f"nation: {org['nation']}")
    if org["parent"]:
        bits.append(f"parent: `{org['parent']}`")
    uc = org.get("unit_code")
    if isinstance(uc, dict) and uc.get("value"):
        bits.append(f"unit: {uc.get('scheme', '?')}:{uc['value']}")
    return " · ".join(bits)


