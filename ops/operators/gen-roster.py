def content_digest(reg: dict) -> str:
    """SHA-256 over the roster *content* (orgs + members) only — deterministic,
    order-canonical, and independent of generated_at. This is the drift key: two
    generations from identical manifests produce the same digest, so a consumer
    (the portal, or `goat access strays`) can tell "is what's deployed the same
    roster my manifests produce?" without diffing every row. Excludes the
    timestamp so a no-content regen stays byte-identical (see main())."""
    body = json.dumps(
        {"orgs": reg["orgs"], "members": reg["members"]},
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def render_json(reg: dict, generated_at: str, digest: str) -> str:
    payload = {
        "_comment": (
            "GENERATED by ops/operators/gen-roster.py — do not hand-edit. "
            "Declared half of the Data-Access COP (docs/design/data-access-cop.md). "
            "'members' is a flat drop-in for the portal access.RosterEntry "
            "(handle/type/org/status); each also carries vendor_tag (the legacy "
            "per-identity short-tag the portal reconciles live Kratos identities "
            "against until the Phase D aff-claim cutover). 'orgs' carries the "
            "affiliation graph (kind/nation/parent) per ADR 1043. Each member's "
            "'collab' is the tracked projection of the manifest collab block "
            " — {state, provider}, never the account id; state is one of "
            "account | declared | none | unrecorded, where 'unrecorded' means the "
            "manifest states nothing and is NOT evidence that no account exists "
            "(reconcile against the provider to learn that). "
            "Each member's 'nationality' is the PERSON's own citizenship from "
            "identity.nationality (ADR 1171) — null means UNDECLARED and is never "
            "filled in from the organisation's nation, which is a separate fact "
            "carried on the org row. 'generated_at' + "
            "'source_digest' let a consumer report roster age + detect a portal "
            "serving a stale copy (source_digest = SHA-256 over orgs+members only)."
        ),
        "generated_at": generated_at,
        "source_digest": digest,
        "orgs": reg["orgs"],
        "members": reg["members"],
    }
    return json.dumps(payload, indent=2, sort_keys=False) + "\n"


def preserved_generated_at(digest: str, out_json: Path = ROSTER_JSON) -> str:
    """Idempotency: if the committed roster.json already carries this exact
    content digest, keep its generated_at so a no-change regen is byte-identical
    (no churn, and `--check` stays green). Only bump the timestamp when the
    content actually changed — which is the only time it's meaningful anyway.

    `out_json` is THIS run's artifact — each goatnet's roster keeps its own
    timestamp, so regenerating one goatnet does not churn another's."""
    if out_json.exists():
        try:
            prev = json.loads(out_json.read_text())
            if isinstance(prev, dict) and prev.get("source_digest") == digest:
                ga = prev.get("generated_at")
                if isinstance(ga, str) and ga:
                    return ga
        except (json.JSONDecodeError, OSError):
            pass  # no or invalid prior roster: regenerate
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _fold_catalog_aliases(reg: dict, catalog: dict) -> dict:
    """Fold a manifest org id that the catalog records as an ALIAS into the org
    it names, moving its members with it.

    WHY THIS EXISTS. An alias is how the registry says "this name and that name
    are the same organisation" — it is the whole mechanism behind the ADR 1112
    org tidy, and the reason a per-person slug like `acme-alice` can be
    reconciled to `acme` without renaming anything (an org id is immutable and
    never re-keys). `gen-roster.py` reads `aliases` here because an alias that
    stays out of the projection the portal consumes is inert: the people stay
    under their per-person slug, and that slug carries no nation, so they have
    no nationality-bearing organisation at all.

    Folding moves the members onto the canonical org and drops the alias row.
    Nothing is lost: the alias id is not a wire anchor (schema.sql:19), so no
    certificate, ACL or Zenoh root moves, and the alias row is still in the
    registry for anyone resolving the old name.

    Facts on the alias row are DISCARDED with a warning rather than merged. An
    alias is by definition not a separate organisation, so a nation or kind
    asserted on one is a claim about the canonical org made in the wrong place;
    the catalog's own value for the canonical org wins immediately below.
    """
    alias_to_canonical: dict = {}
    for corg in catalog.get("orgs", []):
        cid = corg.get("id")
        for alias in corg.get("aliases") or []:
            if alias and cid and alias != cid:
                alias_to_canonical[alias] = cid
    if not alias_to_canonical:
        return reg

    by_id = {o["id"]: o for o in reg["orgs"]}
    keep = []
    for org in reg["orgs"]:
        canonical = alias_to_canonical.get(org["id"])
        if canonical is None or canonical == org["id"]:
            keep.append(org)
            continue
        # The flat member list names the org by id, so it follows the fold on
        # BOTH branches below, because a sole member of an alias org must not
        # point at an id the orgs block no longer carries:
        # check-roster-registry.py refuses that.
        for m in reg["members"]:
            if m.get("org") == org["id"]:
                m["org"] = canonical
        target = by_id.get(canonical)
        if target is None:
            # The canonical org has no manifest members of its own yet; become
            # it, rather than dropping the members on the floor.
            org["id"] = canonical
            by_id[canonical] = org
            keep.append(org)
            continue
        for attr in ("kind", "nation", "composition", "parent"):
            v = org.get(attr)
            if v is not None and target.get(attr) not in (None, v):
                reg["warnings"].append(
                    f"org '{org['id']}' is an alias of '{canonical}' and asserts "
                    f"{attr} '{v}' where '{canonical}' says '{target.get(attr)}' — "
                    f"using '{canonical}', an alias is not a separate organisation"
                )
        target.setdefault("members", []).extend(org.get("members") or [])

    reg["orgs"] = keep
    for org in reg["orgs"]:
        org["members"].sort(key=lambda r: (STATE_ORDER.get(r["state"], 9), r["handle"]))
    reg["members"].sort(key=lambda m: (m["org"], m["handle"]))
    return reg


def apply_org_catalog(reg: dict, catalog: dict) -> dict:
    """Overlay org facts from the committed org catalog (ADR 1112,
    ops/identity/orgs/<env>.yaml, materialized from the console org store by
    ops/scripts/sync-org-catalog.py) onto the manifest-derived registry.

    The catalog is the org-facts SoT in store mode: its parent/kind/nation/
    unit-level fields WIN over manifest aggregation (conflicts are warned, not
    silent), and catalog orgs with no manifest members (chain ancestors) are
    added as member-less org rows — the roster must carry them or the portal
    resolver's parent walk (expandOrg) cannot pass through them.

    An empty catalog is a no-op by construction: the parity gate (design doc
    §13.1) holds because every branch below requires a catalog org row.
    """
    reg = _fold_catalog_aliases(reg, catalog)
    by_id = {o["id"]: o for o in reg["orgs"]}
    for corg in catalog.get("orgs", []):
        cid = corg.get("id")
        if not cid:
            continue
        org = by_id.get(cid)
        if org is None:
            # Member-less ancestor: a real org row so the parent walk works.
            org = {
                "id": cid,
                "kind": corg.get("kind"),
                "nation": normalize_nation(corg.get("nation")) or None,
                "composition": corg.get("composition") or None,
                "parent": corg.get("parent"),
                "members": [],
            }
            reg["orgs"].append(org)
            by_id[cid] = org
            continue
        for attr in ("kind", "nation", "composition", "parent"):
            cval = corg.get(attr)
            if attr == "nation":
                cval = normalize_nation(cval) or None
            if cval is None:
                continue
            if org.get(attr) not in (None, cval):
                reg["warnings"].append(
                    f"org '{cid}': catalog {attr} '{cval}' overrides manifest-derived "
                    f"'{org[attr]}' (the org store is authoritative — reconcile the manifests)"
                )
            org[attr] = cval
    reg["orgs"].sort(key=lambda o: o["id"])
    return reg


def load_org_catalog(path: Path) -> dict:
    """Load the committed org catalog; a missing file is an explicit error in
    store mode (fail loud, not silently flat — the operator asked for the
    store and there is none)."""
    if not path.is_file():
        sys.exit(f"ERROR: --org-source store but no catalog at {path} — run ops/scripts/sync-org-catalog.py first")
    try:
        doc = yaml.safe_load(path.read_text()) or {}
    except yaml.YAMLError as exc:
        sys.exit(f"ERROR: unparseable org catalog {path}: {exc}")
    if not isinstance(doc, dict):
        sys.exit(f"ERROR: org catalog {path} is not a mapping")
    return doc


def catalog_paths_for_every_goatnet() -> list[Path]:
    """Every committed org catalog, sorted — the UNION run only.

    A generation run scoped with `--env` never calls this: it reads
    `ops/identity/orgs/<env>.yaml` and nothing else, because the artifact it
    writes is served to that one goatnet and identity does not cross a goatnet
    boundary (ADR 1172).

    This is the controller-side union at `docs/operators/roster.{md,json}` —
    an index of every environment, read by repo-side tooling on the operator's
    own laptop and deployed nowhere. Where two catalogs disagree about one org,
    the conflict is reported rather than resolved (see merge_org_catalogs) — a
    silent pick is how a registry stops being trustworthy.
    """
    d = REPO / "ops" / "identity" / "orgs"
    return sorted(d.glob("*.yaml"))


def merge_org_catalogs(paths: list[Path], warnings: list) -> dict:
    """Union the given catalogs into one, warning on any disagreement.

    First path wins a conflict, and the conflict is recorded — same rule and
    same visibility as the manifest-side `conflicting <attr>` warnings, so a
    disagreement between two goatnets' curation reads exactly like a
    disagreement between two people's manifests.
    """
    merged: dict = {"orgs": []}
    seen: dict = {}
    for path in paths:
        doc = load_org_catalog(path)
        for org in doc.get("orgs") or []:
            oid = org.get("id")
            if not oid:
                continue
            prior = seen.get(oid)
            if prior is None:
                seen[oid] = org
                merged["orgs"].append(org)
                continue
            for attr in ("kind", "nation", "composition", "parent"):
                a, b = prior.get(attr), org.get(attr)
                if a is not None and b is not None and a != b:
                    warnings.append(
                        f"org '{oid}': catalogs disagree on {attr} "
                        f"('{a}' vs '{b}' in {path.name}) — using first"
                    )
    return merged


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate the sanitized principal-graph registry.")
    ap.add_argument("--check", action="store_true", help="exit 1 if a committed artifact is stale")
    ap.add_argument("--manifests-dir", default=None, help="read manifests from DIR instead of ops/operators/")
    ap.add_argument(
        "--org-source",
        choices=("manifests", "store"),
        default="store",
        help=(
            "where org facts (kind/nation/parent) come from: 'store' (default) = "
            "overlay the committed org catalogs (ADR 1112) — catalog wins on "
            "conflict, member-less chain ancestors are added; 'manifests' = the "
            "legacy per-person aggregation, first-member-wins"
        ),
    )
    ap.add_argument(
        "--org-catalog",
        default=None,
        help="org catalog path for --org-source store (default: ops/identity/orgs/<--env>.yaml)",
    )
    ap.add_argument(
        "--env",
        default=None,
        help=(
            "generate ONE goatnet's artifact: manifests from ops/operators/<env>/, "
            "orgs from ops/identity/orgs/<env>.yaml, written to "
            "docs/operators/<env>/roster.{md,json} — the file that goatnet's portal "
            "is served (ADR 1172). Unset writes the controller-side union at "
            "docs/operators/roster.{md,json}, which is deployed nowhere"
        ),
    )
    ap.add_argument(
        "--operating-sovereign",
        default=os.environ.get("OPERATING_SOVEREIGN", ""),
        help=(
            "ISO 3166-1 alpha-3 nation operating this goatnet (ADR 1151). Used only "
            "to derive affiliation.kind for a manifest that declares sector and no "
            "kind. Unset = the organic question has no answer, and such a manifest "
            "keeps whatever kind it carries rather than being assigned one"
        ),
    )
    args = ap.parse_args()

    base = Path(args.manifests_dir).resolve() if args.manifests_dir else HERE
    if not base.is_dir():
        print(f"ERROR: --manifests-dir not a directory: {base}", file=sys.stderr)
        return 2

    if args.env:
        env_dir = base / args.env
        if not env_dir.is_dir():
            print(
                f"ERROR: no manifest folder for goatnet '{args.env}' at {env_dir}. "
                f"Fill it from that goatnet's own console: "
                f"ops/scripts/sync-onboarded-manifests.py --env {args.env}",
                file=sys.stderr,
            )
            return 2
        flat = len(list(base.glob("*.yml")))
        if flat:
            print(
                f"NOTE: {flat} flat manifest(s) in {base} name no goatnet and are "
                f"excluded from the {args.env} artifact — move each into "
                f"ops/operators/<goatnet>/ (ADR 1172)",
                file=sys.stderr,
            )

    manifests = load_manifests(base, args.env)
    reg = build_registry(manifests, operating_sovereign=args.operating_sovereign)
    if args.org_source == "store":
        if args.org_catalog:
            paths = [Path(args.org_catalog).resolve()]
        elif args.env:
            paths = [REPO / "ops" / "identity" / "orgs" / f"{args.env}.yaml"]
        else:
            paths = catalog_paths_for_every_goatnet()
        reg = apply_org_catalog(reg, merge_org_catalogs(paths, reg["warnings"]))
    for w in reg["warnings"]:
        print(f"WARN: {w}", file=sys.stderr)

    out_md, out_json = artifact_paths(args.env)

    md = render_markdown(reg, args.env)
    digest = content_digest(reg)
    js = render_json(reg, preserved_generated_at(digest, out_json), digest)

    if args.check:
        stale = []
        if (out_md.read_text() if out_md.exists() else "") != md:
            stale.append(str(out_md))
        if (out_json.read_text() if out_json.exists() else "") != js:
            stale.append(str(out_json))
        if stale:
            print(f"STALE: {', '.join(stale)} differ(s) from manifests — run gen-roster.py", file=sys.stderr)
            return 1
        print(f"OK: {out_md.name} + {out_json.name} current ({len(manifests)} manifest(s))")
        return 0

    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text(md)
    out_json.write_text(js)
    print(f"wrote {out_md} + {out_json} ({len(manifests)} manifest(s), {len(reg['orgs'])} org(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
