#!/usr/bin/env python3
"""Generate the sanitized principal-graph registry from the manifests.

The per-entity manifests ``ops/operators/<handle>.yml`` (+ per-env
``ops/operators/<env>/<handle>.yml``) are the source of truth (gitignored —
they carry identity material, backed in 1Password). This script reads them
and regenerates two **committed, public-safe** derived views — the declared
half of the Data-Access COP (docs/design/data-access-cop.md):

  * ``docs/operators/<env>/roster.md``   — human-readable sanitized index.
  * ``docs/operators/<env>/roster.json`` — machine-readable registry artifact
    the goatnet's portal reads; a drop-in for the portal's
    ``access.RosterEntry`` flat list plus the affiliation graph.

ONE ARTIFACT PER GOATNET (ADR 1172). Identity does not cross a goatnet
boundary in either direction, so ``--env <env>`` reads that goatnet's own
manifests (``ops/operators/<env>/``) and its own org catalog
(``ops/identity/orgs/<env>.yaml``), and nothing else reaches the artifact
its portal is served. Running with no ``--env`` writes the union at
``docs/operators/roster.{md,json}``: a CONTROLLER-SIDE index of everyone this
operator has onboarded anywhere, read by repo-side tooling on the operator's
own laptop and **never deployed to a goatnet** — the portal role copies the
per-env artifact and refuses to run without ``portal_roster_env``.

This is the **principal-graph registry** (ADR 1031 Stage 2, identity-grammar
Phase B): org→{person, system} containment, the person→system custody edge,
each member's lifecycle state, and — new in Phase B — the affiliation graph
(``kind`` / ``nation`` / ``parent`` hierarchy from the manifest ``affiliation``
block, ADR 1043). Grouping is by ``affiliation.id`` when present, falling back
to the legacy ``vendor.short_tag`` during migration so every manifest lands
somewhere.

Sanitized: emits handle (kebab, safe), org id + kind + nation + parent (all
safe slugs / ISO codes), type, state, added-date, custody as the enroller's
*handle* (email reverse-mapped; never the raw email), and the collaboration-
environment projection (state + provider slug — never the account id). No
names, no emails, no group memberships.

Collab projection: the manifest `collab` block is the OPERATIONAL
source of truth for who holds a collaboration-environment account, but the
manifests are gitignored, so they need a tracked projection. These fields are
it. They are deliberately four-valued because "the manifest says nothing" and
"the manifest says no account" are different facts, and conflating them hides
accounts — see ``_collab_projection``.

If an index and a manifest disagree, the manifest wins — re-run this.

Usage:
    gen-roster.py [--check] [--env GOATNET] [--manifests-dir DIR]
      --env            : generate ONE goatnet's artifact from that goatnet's own
                         manifests + org catalog, into docs/operators/<env>/.
                         Unset writes the controller-side union (see above).
      --check          : exit 1 if the selected committed artifacts are stale
      --manifests-dir  : read manifests from DIR instead of this script's
                         ops/operators/ (e.g. point at another worktree whose
                         gitignored manifests are present). Output paths are
                         unchanged (this script's repo).
"""
