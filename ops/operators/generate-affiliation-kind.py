#!/usr/bin/env python3
"""Generate the native onboarding sector table from the Ansible derivation source."""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "crates/goat-cli/src/cmd/admin_affiliation_kind.rs"


def render():
    spec = importlib.util.spec_from_file_location("gen_roster", Path(__file__).with_name("gen-roster.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    rows = []
    for sector in sorted(module._SECTOR_TO_TARGET):
        kind = module.derive_kind(sector, "", "")
        if kind is not None:
            rows.append(f"        {json.dumps(sector)} => Some({json.dumps(kind)}),")
    return "\n".join([
        "// Generated by ops/operators/generate-affiliation-kind.py; edit gen-roster.py.",
        "pub(super) fn derive_kind(sector: &str) -> Option<&'static str> {",
        "    match sector.trim().to_ascii_lowercase().as_str() {",
        *rows, "        _ => None,", "    }", "}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.exists() or args.output.read_text() != expected:
            parser.exit(1, "Native affiliation table is stale; run ops/operators/generate-affiliation-kind.py\n")
    else:
        args.output.write_text(expected)


if __name__ == "__main__":
    main()
