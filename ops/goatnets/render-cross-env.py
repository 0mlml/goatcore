"""Render every goatnet's relay-health wiring from ops/goatnets/cross-env.yaml.

    render-cross-env.py            write every group_vars/<group>/cross-env.generated.yml
    render-cross-env.py --check    write nothing; exit 1 on any drift or inconsistency
    render-cross-env.py --boxes    print "<group> <inventory>" per relay-health box
    render-cross-env.py --require <goatnet>
                                   exit 1 unless <goatnet> (a fleet-pins key or a wire
                                   id) has a relay-health box, or declares `absent`

--check is the CI gate (a step in .github/workflows/repo-guards.yml). It fails when:
  - the goatnet keys differ from ops/pins/fleet-pins.yaml or
    ops/validation/goatnet-runners.yaml;
  - an entry is malformed, or a box's inventory group, group_vars directory or
    terraform `module "relay_health_host"` is missing;
  - a generated file is stale, or exists for a group nothing renders;
  - a hand-written group_vars file sets a generated variable;
  - any group_vars value names a public relay-health host that no box serves
    (a mesh-only `relay-health.<site>.netbird.<zone>` name is resolved by that
    goatnet's mesh DNS and is gated there, so it is not checked here).

Canon: docs/design/relay-health-dashboard.md §"One relay-health box per goatnet".
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "ops/goatnets/cross-env.yaml"
FLEET_PINS = REPO / "ops/pins/fleet-pins.yaml"
RUNNERS = REPO / "ops/validation/goatnet-runners.yaml"
GROUP_VARS = REPO / "ops/ansible/group_vars"
ANSIBLE_DIR = REPO / "ops/ansible"
OUT_NAME = "cross-env.generated.yml"
ROLES = {"production", "pre-prod", "dev", "trial"}

BOX_VARS = (
    "relay_health_goatnets",
    "relay_health_summary_goatnet_id",
    "relay_health_summary_targets",
    "relay_health_cross_fleet_allowed",
    "relay_health_cross_fleet_token",
)
# Where a goatnet's hosts publish. Paths are the ingest routes in
# ops/relay/health/relay-metrics-ingest.py (peer names ride the metrics route).
MEMBER_VARS = {
    "host_net_ingest_urls": "host-net-ingest",
    "zenoh_health_ingest_urls": "zenoh-health-ingest",
    "relay_peer_names_ingest_urls": "relay-metrics-ingest",
    "id_admin_console_notify_relay_health_url": "",
    "isitup_relay_health_public_fqdn": None,  # the bare host name
}
OWNED = BOX_VARS + tuple(MEMBER_VARS)
HOST_RE = re.compile(r"relay-health\.[A-Za-z0-9.-]+")
HEADER = """\
# GENERATED by ops/goatnets/render-cross-env.py from ops/goatnets/cross-env.yaml.
# DO NOT EDIT. Change cross-env.yaml, re-run the renderer, and apply with
# ops/goatnets/cross-env-apply.sh. CI refuses a stale copy.
"""


def load(path: Path) -> dict:
    return yaml.safe_load(path.read_text()) or {}


def host_of(url: str) -> str:
    return url.split("://", 1)[-1].split("/", 1)[0]


def validate(doc: dict) -> list[str]:
    errs: list[str] = []
    gns = doc.get("goatnets") or {}
    pins = load(FLEET_PINS).get("goatnets") or {}
    runners = set((load(RUNNERS).get("goatnets") or {}).keys())
    keys = set(gns)
    for name, other in (("ops/pins/fleet-pins.yaml", set(pins)), ("ops/validation/goatnet-runners.yaml", runners)):
        if keys != other:
            errs.append(
                f"goatnet keys differ from {name}: only in cross-env.yaml {sorted(keys - other)}, "
                f"only in {name} {sorted(other - keys)}. Adding or retiring a goatnet changes every roster together."
            )
    ids: set[str] = set()
    for key, g in gns.items():
        where = f"cross-env.yaml goatnets.{key}"
        for f in ("id", "label", "role"):
            if not g.get(f):
                errs.append(f"{where}: missing {f}")
        if g.get("id") in ids:
            errs.append(f"{where}: duplicate id {g.get('id')!r}")
        ids.add(g.get("id"))
        if g.get("role") and g["role"] not in ROLES:
            errs.append(f"{where}: role {g['role']!r} not one of {sorted(ROLES)}")
        rh = g.get("relay_health") or {}
        if bool(rh.get("box")) == bool(rh.get("absent")):
            errs.append(f"{where}.relay_health: set exactly one of box (with url, inventory, terraform) / absent (with the reason)")
            continue
        if rh.get("absent"):
            continue
        box = rh["box"]
        for f in ("url", "inventory", "terraform"):
            if not rh.get(f):
                errs.append(f"{where}.relay_health: box needs {f}")
        if rh.get("url") and not re.fullmatch(r"https://relay-health\.[a-z0-9.-]+/", rh["url"]):
            errs.append(f"{where}.relay_health.url must be https://relay-health.<env>.<zone>/")
        inv = ANSIBLE_DIR / (rh.get("inventory") or "-")
        if rh.get("inventory") and (not inv.is_file() or f"[{box}]" not in inv.read_text()):
            errs.append(f"{where}.relay_health.inventory: {inv.relative_to(REPO)} missing or has no [{box}] group")
        if not (GROUP_VARS / box).is_dir():
            errs.append(f"{where}.relay_health.box: no group_vars/{box}/")
        tf = REPO / (rh.get("terraform") or "-")
        if rh.get("terraform") and not any('module "relay_health_host"' in p.read_text() for p in tf.glob("*.tf")):
            errs.append(f"{where}.relay_health.terraform: {rh['terraform']}/ declares no module \"relay_health_host\"")
        for m in (pins.get(key) or {}).get("members") or []:
            if not (GROUP_VARS / m).is_dir():
                errs.append(f"{where}: fleet-pins member group {m} has no group_vars/{m}/")
    return errs


def render(doc: dict) -> dict[str, dict]:
    """Return {group: vars} for every box and every member group of a goatnet with a box."""
    pins = load(FLEET_PINS).get("goatnets") or {}
    gns = {k: g for k, g in (doc.get("goatnets") or {}).items() if g["relay_health"].get("box")}
    out: dict[str, dict] = {}
    for key, me in gns.items():
        box, url = me["relay_health"]["box"], me["relay_health"]["url"]
        others = [g for g in gns.values() if g is not me]
        registry = [{"id": g["id"], "label": g["label"], "role": g["role"],
                     "url": g["relay_health"]["url"], "local": g is me}
                    for g in [me] + others]
        out[box] = {
            "relay_health_goatnets": registry,
            "relay_health_summary_goatnet_id": me["id"],
            "relay_health_summary_targets": ",".join(g["relay_health"]["url"] + "goatnet-summary-ingest" for g in others),
            "relay_health_cross_fleet_allowed": ",".join(g["id"] for g in others),
            "relay_health_cross_fleet_token": "{{ lookup('env', 'GOAT_CROSS_FLEET_TOKEN') }}",
        }
        member_vars = {}
        for var, path in MEMBER_VARS.items():
            member_vars[var] = host_of(url) if path is None else url + path
        for m in (pins.get(key) or {}).get("members") or []:
            out[m] = dict(member_vars)
    return out


def dump(vars_: dict) -> str:
    return HEADER + yaml.safe_dump(vars_, sort_keys=False, default_flow_style=False, width=200)


def walk_strings(node):
    if isinstance(node, str):
        yield node
    elif isinstance(node, dict):
        for v in node.values():
            yield from walk_strings(v)
    elif isinstance(node, list):
        for v in node:
            yield from walk_strings(v)


def unserved_hosts(served: set[str]) -> list[str]:
    bad = []
    for f in sorted(GROUP_VARS.glob("*/*.yml")):
        try:
            data = load(f)
        except yaml.YAMLError:
            continue
        for s in walk_strings(data):
            if "{{" in s:
                continue
            for h in HOST_RE.findall(s):
                h = h.rstrip(".")
                if h in served or ".netbird." in h:
                    continue
                bad.append(f"{f.relative_to(REPO)}: {h!r} is served by no relay-health box in cross-env.yaml")
    return sorted(set(bad))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--boxes", action="store_true")
    ap.add_argument("--require", metavar="GOATNET")
    a = ap.parse_args()

    doc = load(SRC)
    gns = doc.get("goatnets") or {}
    if a.require:
        want = a.require
        hit = [g for k, g in gns.items() if k in (want, want.replace("-", "_")) or g.get("id") == want]
        if not hit:
            print(f"render-cross-env: {want!r} has no entry in ops/goatnets/cross-env.yaml. Add its relay-health box "
                  f"(terraform module, inventory, group_vars) or `absent` with the reason.", file=sys.stderr)
            return 1
    errs = validate(doc)
    if errs:
        print("render-cross-env: cross-env.yaml is invalid:", file=sys.stderr)
        for e in errs:
            print(f"  - {e}", file=sys.stderr)
        return 1
    if a.require:
        return 0
    if a.boxes:
        for g in gns.values():
            rh = g["relay_health"]
            if rh.get("box"):
                print(rh["box"], rh["inventory"])
        return 0

    rendered = render(doc)
    drift: list[str] = []
    for group, vars_ in rendered.items():
        path = GROUP_VARS / group / OUT_NAME
        want = dump(vars_)
        if a.check:
            if not path.is_file() or path.read_text() != want:
                drift.append(f"{path.relative_to(REPO)} is out of date")
        else:
            path.write_text(want)
            print(f"wrote {path.relative_to(REPO)}")
    for f in sorted(GROUP_VARS.glob("*/*.yml")):
        if f.name == OUT_NAME:
            continue
        try:
            data = load(f)
        except yaml.YAMLError:
            continue
        drift += [f"{f.relative_to(REPO)}: {k} is generated from cross-env.yaml; delete it" for k in OWNED if k in data]
    for stale in sorted(GROUP_VARS.glob(f"*/{OUT_NAME}")):
        if stale.parent.name not in rendered:
            if a.check:
                drift.append(f"{stale.relative_to(REPO)} belongs to no group cross-env.yaml renders")
            else:
                stale.unlink()
                print(f"removed {stale.relative_to(REPO)}")
    served = {host_of(g["relay_health"]["url"]) for g in gns.values() if g["relay_health"].get("box")}
    drift += unserved_hosts(served)
    if drift:
        print("render-cross-env: drift:", file=sys.stderr)
        for d in drift:
            print(f"  - {d}", file=sys.stderr)
        print("Fix: edit cross-env.yaml or the named file, run python3 ops/goatnets/render-cross-env.py, commit.", file=sys.stderr)
        return 1
    if a.check:
        boxes = sum(1 for g in gns.values() if g["relay_health"].get("box"))
        print(f"render-cross-env: OK — {boxes} box(es), {len(rendered) - boxes} member group(s); "
              f"roster matches fleet-pins + goatnet-runners; every relay-health host is served")
    return 0


if __name__ == "__main__":
    sys.exit(main())
