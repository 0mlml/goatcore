-- orgstore schema — the first-class org registry (ADR 1112,
-- docs/design/org-hierarchy-and-dedup.md §3). Orgs are created, parented,
-- aliased, and (increment 3) merged as deliberate audited acts; the roster
-- projection reads org facts from the generated committed catalog this store
-- materializes, instead of aggregating them from per-person manifests.
--
-- Migration version 1 on Postgres (ADR 1165 step A): the SQLite schema with the
-- tables and columns unchanged, in its own database beside the onboarding
-- store's. Type map: INTEGER -> BIGINT, TEXT -> TEXT COLLATE "C" (SQLite's
-- BINARY ordering), INTEGER PRIMARY KEY AUTOINCREMENT -> BIGINT GENERATED BY
-- DEFAULT AS IDENTITY under the same column name.
--
-- Idempotent: every statement is CREATE ... IF NOT EXISTS. Deprecate-never-
-- delete: rows are statused, never removed.

CREATE TABLE IF NOT EXISTS orgs (
    -- Kebab slug, the existing affiliation.id charset (manifest schema).
    -- IMMUTABLE — never renamed; a rename is a merge into a new org
    -- (alias absorption, increment 3). The id is deliberately absent from
    -- every wire anchor (ADR 1043/1025), which is what makes attach-never-
    -- re-key true by construction.
    id            TEXT COLLATE "C" PRIMARY KEY,
    display_name  TEXT COLLATE "C" NOT NULL DEFAULT '',
    -- vendor | organic | partner | civil ('' = not yet declared).
    -- DEPRECATED by ADR 1151: it asks two independent questions at once (what
    -- legal kind of thing, and ours-or-foreign). Still written and still read
    -- during the migration window, but DERIVED from sector + gov_branch +
    -- the organic test whenever those are present. Never delete the column —
    -- deprecate-never-delete, and rollback is a file-level lever.
    kind          TEXT COLLATE "C" NOT NULL DEFAULT '',
    -- ADR 1171. national | multinational ('' = not yet declared). Decides what
    -- `nation` below MEANS on this row: for `national` it is the owning
    -- sovereign's alpha-3 code, for `multinational` it is a body marker (NATO,
    -- EU) and the nations that staff it are contributors, not owners. It is also
    -- what makes a `constituent` membership refusable on a national org, whose
    -- ownership is fixed at creation and which no membership may change.
    composition   TEXT COLLATE "C" NOT NULL DEFAULT '',
    -- ADR 1151 target block. state | commercial | civil-society ('' = not yet
    -- declared): a government body, a company (including state-owned), or an
    -- NGO / university / press organisation. The ADR 1077 legacy values are
    -- still accepted here during the migration window. Rationale: ADR 1151.
    sector        TEXT COLLATE "C" NOT NULL DEFAULT '',
    -- ADR 1151. military | law-enforcement | intelligence | civil ('' = none),
    -- and MEANINGFUL ONLY when sector = state. This is the branch-of-government
    -- that used to sit inside the flat sector list beside `commercial`.
    gov_branch    TEXT COLLATE "C" NOT NULL DEFAULT '',
    -- ISO 3166-1 alpha-3, or NATO/EU ('' = none).
    nation        TEXT COLLATE "C" NOT NULL DEFAULT '',
    -- Display-only hint (nation/service/command/unit). NOTHING dispatches on
    -- this — the chain is whatever depth reality has (design §4).
    echelon_hint  TEXT COLLATE "C" NOT NULL DEFAULT '',
    -- ADR 1064 provenance grades: authoritative | operator-verified |
    -- open-source | self-asserted. Attribution, never a gate.
    provenance    TEXT COLLATE "C" NOT NULL DEFAULT 'self-asserted',
    -- active | absorbed (merge target recorded via org_aliases kind
    -- 'absorbed-id'; increment 3).
    status        TEXT COLLATE "C" NOT NULL DEFAULT 'active',
    created_by    TEXT COLLATE "C" NOT NULL DEFAULT '',
    created_at    BIGINT NOT NULL
);

-- Effective-dated vertical containment (the grammar's v1 `parent` edge,
-- identity-grammar.md §3). Bitemporal per ADR 1051: valid_from/valid_to is
-- valid-time, recorded_at is transaction-time. At most ONE open edge
-- (valid_to IS NULL) per org — enforced in store.go (SetParent closes the
-- open edge before inserting), backstopped by the partial unique index.
-- History survives: a reorg closes an edge, never deletes it.
CREATE TABLE IF NOT EXISTS org_parent_edges (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id        TEXT COLLATE "C" NOT NULL REFERENCES orgs(id),
    parent_id     TEXT COLLATE "C" NOT NULL REFERENCES orgs(id),
    valid_from    BIGINT NOT NULL,
    valid_to      BIGINT,            -- NULL = open (the current parent)
    recorded_at   BIGINT NOT NULL,
    actor         TEXT COLLATE "C" NOT NULL DEFAULT '',
    justification TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS org_parent_edges_org_idx    ON org_parent_edges(org_id);
CREATE INDEX IF NOT EXISTS org_parent_edges_parent_idx ON org_parent_edges(parent_id);
CREATE UNIQUE INDEX IF NOT EXISTS org_parent_edges_one_open
    ON org_parent_edges(org_id) WHERE valid_to IS NULL;

-- Alias table: name variants + abbreviations accreted by confirmed matches
-- (increment 2) and absorbed ids from merges (increment 3). An alias resolves
-- to its canonical org at every consumer; an alias may never collide with an
-- org id (enforced in store.go — the two namespaces are one).
CREATE TABLE IF NOT EXISTS org_aliases (
    alias       TEXT COLLATE "C" PRIMARY KEY,
    org_id      TEXT COLLATE "C" NOT NULL REFERENCES orgs(id),
    -- name-variant | abbreviation | absorbed-id
    kind        TEXT COLLATE "C" NOT NULL DEFAULT 'name-variant',
    recorded_at BIGINT NOT NULL,
    actor       TEXT COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS org_aliases_org_idx ON org_aliases(org_id);

-- Negative match evidence (design §7): the operator explicitly created or
-- kept a DIFFERENT org despite this candidate being offered for this typed
-- name. Suggest demotes (never hides) the pair. name_norm is the
-- NormalizeName() form — one row per (name family, candidate).
CREATE TABLE IF NOT EXISTS org_match_overrides (
    name_norm   TEXT COLLATE "C" NOT NULL,
    org_id      TEXT COLLATE "C" NOT NULL REFERENCES orgs(id),
    recorded_at BIGINT NOT NULL,
    actor       TEXT COLLATE "C" NOT NULL DEFAULT '',
    PRIMARY KEY (name_norm, org_id)
);
