package access

import (
	"encoding/json"
	"fmt"
	"os"
)

// LoadRosterFreshness reads only the provenance stamp (generated_at +
// source_digest) and member count from roster.json, plus the file mtime, so the
// COP can report how current the declared registry is. A file that predates the
// gen-roster.py stamp yields empty generated_at/source_digest (still valid — the
// caller degrades to "age unknown"). A missing/unreadable file returns nil, not
// an error: freshness is advisory, and the load path already surfaces a hard
// read error as a warning.
func LoadRosterFreshness(path string) *RosterFreshness {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil
	}
	var stamp struct {
		GeneratedAt  string            `json:"generated_at"`
		SourceDigest string            `json:"source_digest"`
		Members      []json.RawMessage `json:"members"`
	}
	if err := json.Unmarshal(raw, &stamp); err != nil {
		return nil
	}
	fr := &RosterFreshness{
		GeneratedAt:  stamp.GeneratedAt,
		SourceDigest: stamp.SourceDigest,
		MemberCount:  len(stamp.Members),
	}
	if fi, err := os.Stat(path); err == nil {
		fr.LoadedUnix = fi.ModTime().Unix()
	}
	return fr
}

// roster.go loads the declared-half registry artifact docs/operators/roster.json
// (generated by ops/operators/gen-roster.py) into the []RosterEntry the access
// graph reconciles live identities against. Two-key model post-Phase D
// (ADR 1043): RosterEntry.OrgID always carries the true affiliation.id (the
// shared unit the registry groups on) — the key an aff-carrying live identity
// (traits.aff.id) reconciles against. RosterEntry.Org remains the legacy key —
// each member's vendor_tag (the value traits.vendor.short_tag presents),
// falling back to the affiliation org id when a member has no vendor tag — for
// identities minted before the Phase D aff claim.

// rosterFile mirrors the on-disk roster.json shape. The flat member list drives
// reconciliation; the orgs block carries the affiliation graph (kind/nation per
// org id, ADR 1043) which the COP surfaces — a member's affiliation is its
// org's, joined here in Go (the member rows carry no affiliation of their own).
type rosterFile struct {
	Orgs    []rosterOrg    `json:"orgs"`
	Members []rosterMember `json:"members"`
}

// rosterOrg is one org's affiliation attributes from roster.json `orgs[]`. ID is
// affiliation.id (or the legacy vendor short-tag the generator grouped on); Kind
// is vendor|organic|partner; Nation is the ISO code of the nation that OWNS the
// organisation. A member inherits kind and nation from the org it belongs to —
// but NOT its own nationality, which is a per-person fact carried on the member
// row (ADR 1171).
type rosterOrg struct {
	ID     string `json:"id"`
	Kind   string `json:"kind"`
	Nation string `json:"nation"`
}

type rosterMember struct {
	Handle    string `json:"handle"`
	Type      string `json:"type"`
	Org       string `json:"org"`        // affiliation.id (the true unit)
	VendorTag string `json:"vendor_tag"` // legacy per-identity short-tag (may be empty)
	Status    string `json:"status"`
	EmailHash string `json:"email_hash"` // SHA-256(lowercased email) — the tag-independent reconcile key
	// The PERSON's own citizenship (ADR 1171), absent/null when undeclared.
	// Distinct from the org's Nation, which lives on the org row above.
	Nationality string `json:"nationality"`
}

// LoadRoster reads roster.json at path and returns the declared roster as
// []RosterEntry, keyed (Org) on the value the live identity layer reconciles
// against (vendor_tag, else the affiliation org id). A missing path is not an
// error to the caller's policy — that is handled at the call site — but an
// unreadable or malformed file is, so a silently-empty roster can't be mistaken
// for "everyone cut off".
func LoadRoster(path string) ([]RosterEntry, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read roster %s: %w", path, err)
	}
	var rf rosterFile
	if err := json.Unmarshal(raw, &rf); err != nil {
		return nil, fmt.Errorf("parse roster %s: %w", path, err)
	}
	// Affiliation lives at the org level; index it by org id so each member can
	// inherit its org's kind/nation (the Go-side join — members carry no
	// affiliation of their own).
	affByOrg := make(map[string]rosterOrg, len(rf.Orgs))
	for _, o := range rf.Orgs {
		affByOrg[o.ID] = o
	}
	out := make([]RosterEntry, 0, len(rf.Members))
	for _, m := range rf.Members {
		// Affiliation joins on the member's real org id (m.Org), independent of
		// the vendor_tag substitution used as the reconciliation key below.
		aff := affByOrg[m.Org]
		org := m.VendorTag
		if org == "" {
			org = m.Org
		}
		out = append(out, RosterEntry{
			Handle:      m.Handle,
			Type:        m.Type,
			Org:         org,
			OrgID:       m.Org,
			Status:      m.Status,
			Affiliation: aff.Kind,
			// The org's nation, inherited — this one IS an org fact.
			Nation: aff.Nation,
			// The person's own, NOT inherited. A member whose manifest declares
			// no nationality stays empty; filling it from aff.Nation is the
			// assumption ADR 1171 removes, and it would turn "we do not know"
			// into an assertion nobody made.
			Nationality: m.Nationality,
			EmailHash:   m.EmailHash,
		})
	}
	return out, nil
}
