#!/usr/bin/env python3
"""Generate SPIRE registration-entry definitions from PLATFORM workload declarations.

ADR 1098 (machine-enrollment stage 4, Option B) — the portal RECORDS a PLATFORM's
declared sub-workload composition (`slots.workloads`); SPIRE owns the actual
workload SVIDs. This is the bridge: it reads the portal's enrolled PLATFORMs and
emits the `spire_registration_entries`-shaped definitions the `spire` Ansible role
reconciles.

Workload-identity model (ADR 1098 §Workload identity):
  - A workload SVID's **CN = the platform's slot anchor** (its cert CN / Zenoh ACL
    subject), so the workload composes under the platform's write-namespace exactly
    as the platform does — "compose by CN". Workloads are NOT separately
    wire-distinguishable; they share the platform's namespace.
  - A workload's **spiffe_id = <platform-handle>/<function>** (lowercased), distinct
    per function — the SPIFFE attribution that separates sensor from effector.
  - The **selector is deploy-time**: it's a docker label matching the workload's
    runtime sidecar, which only exists once the platform's containers are defined.
    This generator emits `selector: null` + a `NEEDS_DEPLOY_SELECTOR` marker; the
    operator fills it (or the deploy overlay does) before the role registers the
    entry. The role skips-with-warning any entry still missing a selector, so a
    half-declared platform never silently fails to register.

Usage:
    ops/identity/gen-platform-spire-entries.py --env zagros [--out <path>]

Reads the portal at $PORTAL_URL (default per --env) with the operator bearer from
$<ENV>_PORTAL_OPERATOR_API_KEY (then $PORTAL_OPERATOR_API_KEY). Emits YAML to --out
(default stdout). Deterministic + idempotent: same portal state → same output.
"""

import argparse
import json
import os
import sys
import urllib.request


def portal_get(base_url, path, key):
    req = urllib.request.Request(
        base_url.rstrip("/") + path,
        headers={"Authorization": "Bearer " + key},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310 (mesh-internal portal)
        return json.loads(resp.read().decode())


def platform_entries(machines):
    """Turn the portal's /api/machines list into SPIRE entry definitions, one per
    (platform, workload). Only PLATFORM machines carrying a workload composition
    contribute. Sorted for deterministic output."""
    entries = []
    for m in machines:
        if m.get("node_class") != "PLATFORM":
            continue
        anchor = m.get("slot_id", "")
        handle = m.get("system_handle", "") or anchor
        for w in m.get("workloads", []) or []:
            func = w.strip().lower()
            if not func:
                continue
            entries.append(
                {
                    "spiffe_id": f"{handle}/{func}",
                    # SVID CN = the platform's slot anchor (the Zenoh ACL subject the
                    # workload composes under). SPIRE sets CN = the first -dns.
                    "cn_dns_name": anchor,
                    "selector": None,  # NEEDS_DEPLOY_SELECTOR — a docker:label:... the operator fills
                    "platform": handle,
                    "platform_anchor": anchor,
                    "workload_class": w.strip().upper(),
                }
            )
    entries.sort(key=lambda e: (e["platform"], e["spiffe_id"]))
    return entries


def to_yaml(entries):
    """Emit a minimal, dependency-free YAML block (no PyYAML needed — the shape is
    fixed and flat)."""
    out = [
        "# GENERATED by ops/identity/gen-platform-spire-entries.py — do not edit.",
        "# Source: portal-recorded PLATFORM workload declarations (ADR 1098, Option B).",
        "# Each entry still needs its deploy-time `selector` filled before the spire",
        "# role will register it (NEEDS_DEPLOY_SELECTOR). The role skips+warns until then.",
        "spire_platform_workload_entries:",
    ]
    if not entries:
        out[-1] += " []"
        return "\n".join(out) + "\n"
    for e in entries:
        sel = "null  # NEEDS_DEPLOY_SELECTOR (docker:label:...)" if e["selector"] is None else f'"{e["selector"]}"'
        out += [
            f'  - spiffe_id: "{e["spiffe_id"]}"',
            f'    cn_dns_name: "{e["cn_dns_name"]}"',
            f"    selector: {sel}",
            f'    platform: "{e["platform"]}"',
            f'    workload_class: "{e["workload_class"]}"',
        ]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate SPIRE entries from PLATFORM workload declarations (ADR 1098).")
    ap.add_argument("--env", default="zagros", help="goatnet env (selects the operator-key env var + default portal URL)")
    ap.add_argument("--portal-url", default=os.environ.get("PORTAL_URL", ""), help="override the portal base URL")
    ap.add_argument("--out", default="-", help="output path, or - for stdout (default)")
    args = ap.parse_args(argv)

    env_up = args.env.upper().replace("-", "_")
    key = os.environ.get(f"{env_up}_PORTAL_OPERATOR_API_KEY") or os.environ.get("PORTAL_OPERATOR_API_KEY")
    if not key:
        sys.exit(f"error: no operator key in ${env_up}_PORTAL_OPERATOR_API_KEY or $PORTAL_OPERATOR_API_KEY")
    base = args.portal_url or os.environ.get("PORTAL_URL")
    if not base:
        sys.exit("error: no portal URL (set --portal-url or $PORTAL_URL)")

    body = portal_get(base, "/api/machines", key)
    entries = platform_entries(body.get("machines", []))
    yaml = to_yaml(entries)

    if args.out == "-":
        sys.stdout.write(yaml)
    else:
        with open(args.out, "w") as f:
            f.write(yaml)
        sys.stderr.write(f"wrote {len(entries)} platform-workload entr{'y' if len(entries) == 1 else 'ies'} to {args.out}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
