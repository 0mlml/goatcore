#!/usr/bin/env python3
"""Generate this repository's goatbuilder config from its sources of record.

goatbuilder.yaml is never hand-maintained: every fact in it already has a home
— the components in ops/pins/fleet-pins.yaml, the environments and the
promotion path in ops/release/ladder.yaml — and a second copy of those facts
would only drift. This script derives the config from them and emits only what
they evidence; a field they do not carry (a transport, an inventory) is left
out, and the schema keeps it optional.

Usage:
    ./gen-config.py            # (re)write ops/goatbuilder/goatbuilder.yaml
    ./gen-config.py --check    # exit 1 if the committed file is not what the
                               # sources would generate (the CI drift gate)

Exit codes: 0 ok, 1 drift (--check), 2 usage / missing dependency / bad source.
"""
from __future__ import annotations

import argparse
import os
import sys

try:
    import yaml
except ImportError:
    sys.stderr.write("ERROR: PyYAML is required: pip install pyyaml\n")
    sys.exit(2)

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
PINS = os.path.join(REPO, "ops", "pins", "fleet-pins.yaml")
LADDER = os.path.join(REPO, "ops", "release", "ladder.yaml")
OUT = os.path.join(HERE, "goatbuilder.yaml")

HEADER = (
    "# GENERATED by ops/goatbuilder/gen-config.py from ops/pins/fleet-pins.yaml and\n"
    "# ops/release/ladder.yaml — do not edit; change the source and regenerate.\n"
    "# Validated against ops/goatbuilder/schema/goatbuilder-v1.schema.json\n"
    "# (docs/design/goatbuilder.md, ADR 1198).\n"
)


def generate(pins_path: str = PINS, ladder_path: str = LADDER) -> dict:
    """Return the config dict the two sources of record evidence."""
    with open(pins_path) as fh:
        pins = yaml.safe_load(fh) or {}
    with open(ladder_path) as fh:
        ladder = yaml.safe_load(fh) or {}

    components: dict[str, dict] = {}
    for name in sorted(pins.get("components") or {}):
        c = pins["components"][name] or {}
        wf = c.get("image_workflow")
        comp: dict = {
            "image_workflow": os.path.basename(wf) if wf else None,
            "declared_in": "ops/pins/fleet-pins.yaml",
        }
        if c.get("var"):
            comp["var"] = c["var"]
        ledger = c.get("ledger_component") or name
        if ledger != name:
            comp["ledger"] = ledger
        components[name] = comp

    rungs = [r for r in ladder.get("rungs") or [] if r.get("status") == "live"]
    if not rungs:
        sys.exit("ERROR: ladder.yaml has no live rungs")
    goatnets = pins.get("goatnets") or {}
    environments = []
    for r in rungs:
        env = {"name": r["goatnet"], "converger": "push-ansible"}
        members = (goatnets.get(r["goatnet"]) or {}).get("members") or []
        if members:
            env["groups"] = list(members)
        environments.append(env)

    gates_into: dict[str, list] = {}
    for hop in ladder.get("hops") or []:
        if hop.get("status") != "live":
            continue
        gates = []
        for g in hop.get("gates") or []:
            gate = {"id": g["id"]}
            if "min_days" in g:
                gate["min_days"] = int(g["min_days"])
            gates.append(gate)
        gates_into[hop["to"]] = gates

    path = []
    for r in rungs:
        stage = {"name": r["name"], "kind": "rung", "environment": r["goatnet"]}
        if gates_into.get(r["name"]):
            stage["gates"] = gates_into[r["name"]]
        path.append(stage)

    return {
        "schema": "goatbuilder/v1",
        "preset": "full",
        "repo": {
            "source": "USAREUR-AF/goatcore",
            "image_namespace": "ghcr.io/usareur-af",
            "signing": "intent-sign",
        },
        # goat's own; another project declares its own (goatbuilder-portability.md).
        "deploy": {"aws_profile": "usareur-af", "ssh_user": "goat", "state_dir": "~/.goat/state"},
        "components": components,
        "environments": environments,
        "promotion": {"path": path},
        # The secrets posture (ADR 1204), declared in ops/goatbuilder/posture.yml.
        # goat's own is references resolved by 1Password per command (ADR 1186),
        # with op_account pinning the account op:// references resolve against so
        # `op` can never prompt across every configured account; OP_ACCOUNT in the
        # environment overrides it per command. A checkout that declares no
        # posture gets the store that needs no account of anyone's: an env file,
        # which `goatbuilder secrets init` can write with strong random values.
        "secrets": posture(),
    }


def posture() -> dict:
    """The `secrets:` block, from ops/goatbuilder/posture.yml where it exists."""
    path = os.path.join(REPO, "ops/goatbuilder/posture.yml")
    try:
        with open(path, encoding="utf-8") as fh:
            declared = yaml.safe_load(fh) or {}
    except OSError:
        return {"store": "env-file"}
    if not isinstance(declared, dict) or not declared.get("store"):
        raise SystemExit(f"{path} declares no secrets store: add `store: <name>` (ADR 1204)")
    return {k: v for k, v in declared.items() if v not in (None, "")}


def render(config: dict) -> str:
    return HEADER + yaml.safe_dump(config, sort_keys=False, default_flow_style=False, width=100)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed config differs from the generated one")
    a = ap.parse_args()
    text = render(generate())
    if a.check:
        try:
            with open(OUT) as fh:
                committed = fh.read()
        except FileNotFoundError:
            sys.exit(f"DRIFT: {os.path.relpath(OUT, REPO)} is missing; run ops/goatbuilder/gen-config.py")
        if committed != text:
            sys.exit(f"DRIFT: {os.path.relpath(OUT, REPO)} differs from what the sources generate; run ops/goatbuilder/gen-config.py")
        print(f"ok: {os.path.relpath(OUT, REPO)} matches its sources")
        return
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, REPO)}")


if __name__ == "__main__":
    main()
