#!/usr/bin/env bash
# parity-pins.sh — the parity gate for `goatbuilder pins` against
# ops/pins/generate-pins.py (goatbuilder-conformance.md §The parity gate:
# byte-identical generated pins and intents).
#
# Three runs, on a scratch copy of the tree so nothing committed moves:
#   1. --check on the tree as committed: both sides pass, same last line.
#   2. a DRIFTED copy (one deviation moved to a new digest): both --check
#      refuse, with the same FAIL lines; then both regenerate, and every
#      group_vars/<member>/pins.yml is byte-identical, every intent.json
#      identical but for `generated_at` (the clock); the regenerated copies
#      then pass --check on both sides.
#   3. idempotence: a SECOND regeneration on the regenerated copy changes no
#      byte and reports no stale signature — the rule that keeps a re-run
#      from landing a pull request of nothing but .sig files.
# The unified diffs the two --check runs print are not compared line for
# line: difflib and the binary's differ pick different context alignments
# for the same change; the FAIL lines and the verdicts are what is compared.
#
# usage: parity-pins.sh <goatbuilder binary>
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"; REPO="$(cd "$HERE/../.." && pwd)"
BIN="${1:?}"
SCRATCH="$(mktemp -d)"; trap 'rm -rf "$SCRATCH"' EXIT

strip_rows() { sed -E 's/^(ok    pins|FAIL  pins)  //' | grep -v '^pins: ' | grep -v '^  ' | grep -v 'generated_at'; }
rows_all() { sed -E 's/^(ok    pins|FAIL  pins)  //' | grep -v '^pins: ' | grep -v 'generated_at'; }
script_check() { ( cd "$1" && python3 ops/pins/generate-pins.py --check 2>&1 | grep -v '^  ' | grep -v 'generated_at' ) || true; }
binary_check() { "$BIN" -C "$1" pins --check 2>&1 | strip_rows || true; }
fail=0
compare() { # $1 label $2 a $3 b
  if [ "$2" != "$3" ]; then fail=1; echo "PARITY FAIL: $1"; { diff <(printf '%s\n' "$2") <(printf '%s\n' "$3") || true; } | sed 's/^/    /' | head -30
  else echo "parity ok: $1 ($(printf '%s\n' "$2" | grep -c .) lines identical)"; fi
}

# 1. the committed tree
compare "pins --check on the committed tree" "$(script_check "$REPO")" "$(binary_check "$REPO")"

# 2. a drifted copy, each side its own
for side in py rs; do
  mkdir -p "$SCRATCH/$side"
  ( cd "$REPO" && tar cf - ops/pins ops/ansible/group_vars ops/ansible/roles ops/consistency ops/enrollment/public-keys ops/release 2>/dev/null ) | ( cd "$SCRATCH/$side" && tar xf - )
  python3 - "$SCRATCH/$side/ops/pins/fleet-pins.yaml" <<'PY'
import re, sys
p = sys.argv[1]; s = open(p).read()
m = re.search(r'value: "([^"]*@sha256:)([0-9a-f]{64})"', s)
if not m: sys.exit("no deviation value to move")
new = ("1" * 64) if m.group(2) != "1" * 64 else ("2" * 64)
open(p, "w").write(s[:m.start(2)] + new + s[m.end(2):])
PY
done
compare "pins --check on a drifted copy" "$(script_check "$SCRATCH/py")" "$(binary_check "$SCRATCH/rs")"
a="$( cd "$SCRATCH/py" && python3 ops/pins/generate-pins.py 2>&1 | grep -v 'generated_at' )"
b="$( "$BIN" -C "$SCRATCH/rs" pins 2>&1 | rows_all )"
compare "pins (regenerate) on a drifted copy" "$a" "$b"
n=0
for d in "$SCRATCH/py"/ops/ansible/group_vars/*/; do
  m="$(basename "$d")"; [ -f "$d/pins.yml" ] || continue
  if ! cmp -s "$d/pins.yml" "$SCRATCH/rs/ops/ansible/group_vars/$m/pins.yml"; then fail=1; echo "PARITY FAIL: group_vars/$m/pins.yml differs"; { diff "$d/pins.yml" "$SCRATCH/rs/ops/ansible/group_vars/$m/pins.yml" || true; } | head -10 | sed 's/^/    /'; fi
  n=$((n + 1))
done
for d in "$SCRATCH/py"/ops/consistency/intent/*/; do
  g="$(basename "$d")"
  if ! diff -q <(grep -v '"generated_at"' "$d/intent.json") <(grep -v '"generated_at"' "$SCRATCH/rs/ops/consistency/intent/$g/intent.json") >/dev/null; then
    fail=1; echo "PARITY FAIL: intent/$g/intent.json differs"; { diff <(grep -v '"generated_at"' "$d/intent.json") <(grep -v '"generated_at"' "$SCRATCH/rs/ops/consistency/intent/$g/intent.json") || true; } | head -10 | sed 's/^/    /'
  fi
  n=$((n + 1))
done
[ "${n:-0}" -gt 0 ] || { echo "parity FAIL: nothing was compared (no inputs read — is PyYAML importable by python3?)"; exit 1; }
[ "$fail" = 0 ] && echo "parity ok: $n generated files byte-identical (intents modulo generated_at)"

# 3. idempotence: a second run changes nothing and says so
before="$( cd "$SCRATCH/rs" && find ops/ansible/group_vars ops/consistency/intent -name 'pins.yml' -o -name 'intent.json' | sort | xargs shasum )"
second="$( "$BIN" -C "$SCRATCH/rs" pins 2>&1 | rows_all )"
after="$( cd "$SCRATCH/rs" && find ops/ansible/group_vars ops/consistency/intent -name 'pins.yml' -o -name 'intent.json' | sort | xargs shasum )"
if [ "$before" != "$after" ]; then fail=1; echo "PARITY FAIL: a second `pins` run changed generated bytes"; fi
if printf '%s\n' "$second" | grep -q 'STALE'; then fail=1; echo "PARITY FAIL: a second \`pins\` run reported a stale signature on an unchanged intent"; fi
second_py="$( cd "$SCRATCH/py" && python3 ops/pins/generate-pins.py 2>&1 )"
if printf '%s\n' "$second_py" | grep -q 'STALE'; then fail=1; echo "PARITY FAIL: a second generate-pins.py run reported a stale signature on an unchanged intent"; fi
[ "$fail" = 0 ] && echo "parity ok: a second regeneration is a byte no-op on both sides (nothing to re-sign, nothing to land)"
exit $fail
