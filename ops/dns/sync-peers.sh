#!/usr/bin/env bash
set -euo pipefail

# goat — Sync Netbird peers to CoreDNS hosts file
#
# Queries the Netbird management API for all peers and generates
# the mesh-hosts file for CoreDNS. Reloads CoreDNS after update.
#
# Designed to run ON the router (where CoreDNS runs) via cron.
# Also works from an admin machine for testing (won't reload dnsmasq).
#
# Prerequisites:
#   - NETBIRD_API_TOKEN set (create a PAT in the dashboard: Users → Personal Access Tokens)
#   - NETBIRD_DOMAIN set (the mesh DNS zone; .envrc exports it, and the
#     cron entry --install-cron writes carries it)
#   - curl, python3 available
#
# Usage:
#   bash sync-peers.sh                    # one-shot sync
#   bash sync-peers.sh --install-cron     # install 5-minute cron job on the router
#
# The script preserves any lines in mesh-hosts below a "# Custom entries" marker.

DOMAIN="${NETBIRD_DOMAIN:?Set NETBIRD_DOMAIN (the mesh DNS zone)}"
API_URL="https://${DOMAIN}/api"

# Detect if running on the router or admin machine
if [ -d "/opt/goat/dns" ]; then
  HOSTS_FILE="/opt/goat/dns/mesh-hosts"
  DNS_DIR="/opt/goat/dns"
  ON_ROUTER=true
else
  SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
  HOSTS_FILE="$SCRIPT_DIR/mesh-hosts"
  DNS_DIR="$SCRIPT_DIR"
  ON_ROUTER=false
fi

# Install cron job
if [ "${1:-}" = "--install-cron" ]; then
  if [ "$ON_ROUTER" != "true" ]; then
    echo "ERROR: --install-cron must be run on the router."
    exit 1
  fi
  CRON_CMD="NETBIRD_API_TOKEN=$NETBIRD_API_TOKEN NETBIRD_DOMAIN=$DOMAIN /opt/goat/dns/sync-peers.sh >> /var/log/sync-peers.log 2>&1"
  (crontab -l 2>/dev/null | grep -v sync-peers; echo "*/5 * * * * $CRON_CMD") | crontab -
  echo "Cron job installed: every 5 minutes."
  echo "Logs: /var/log/sync-peers.log"
  exit 0
fi

: "${NETBIRD_API_TOKEN:?Set NETBIRD_API_TOKEN (create a PAT in the Netbird dashboard: Users → Personal Access Tokens)}"

# Query the Netbird API for all peers
PEERS=$(curl -sk -H "Authorization: Token $NETBIRD_API_TOKEN" \
  -H "Accept: application/json" \
  "$API_URL/peers" 2>/dev/null)

if [ -z "$PEERS" ] || echo "$PEERS" | grep -q '"code"'; then
  echo "$(date): ERROR: Could not fetch peers from API."
  echo "$PEERS"
  exit 1
fi

# Extract custom entries from existing hosts file (anything below "# Custom entries")
CUSTOM_ENTRIES=""
if [ -f "$HOSTS_FILE" ]; then
  CUSTOM_ENTRIES=$(sed -n '/^# Custom entries/,$p' "$HOSTS_FILE" 2>/dev/null || true)
fi

# Generate hosts file from API response
TEMP_HOSTS=$(mktemp)
cat > "$TEMP_HOSTS" << 'HEADER'
# goat — mesh peer DNS records
# Auto-generated by sync-peers.sh — do not edit above the "Custom entries" line.
# Manual additions go below "# Custom entries" and will be preserved across syncs.

# Peers (auto-synced from Netbird API)
HEADER

echo "$PEERS" | python3 -c "
import sys, json

data = json.load(sys.stdin)
domain = '${DOMAIN}'
custom = '''${CUSTOM_ENTRIES}'''

# Collect FQDNs already claimed in the custom entries section.
# If a peer's FQDN appears there (e.g., as a service pointed at the network host),
# emit only the short alias so dnsmasq doesn't return two IPs.
custom_fqdns = set()
for line in custom.splitlines():
    parts = line.split()
    if parts and not parts[0].startswith('#'):
        for h in parts[1:]:
            custom_fqdns.add(h)

for peer in sorted(data, key=lambda p: p.get('name', '')):
    name = peer.get('name', '').lower().replace(' ', '-')
    ip = peer.get('ip', '').split('/')[0]
    if name and ip:
        fqdn = f'{name}.{domain}'
        if fqdn in custom_fqdns:
            print(f'{ip}  {name}')
        else:
            print(f'{ip}  {name}.{domain} {name}')
" >> "$TEMP_HOSTS"

# Append custom entries
if [ -n "$CUSTOM_ENTRIES" ]; then
  echo "" >> "$TEMP_HOSTS"
  echo "$CUSTOM_ENTRIES" >> "$TEMP_HOSTS"
else
  echo "" >> "$TEMP_HOSTS"
  echo "# Custom entries (add manual DNS entries below this line — they survive sync)" >> "$TEMP_HOSTS"
fi

# Compare with current file
if [ -f "$HOSTS_FILE" ] && diff -q "$TEMP_HOSTS" "$HOSTS_FILE" >/dev/null 2>&1; then
  rm "$TEMP_HOSTS"
  exit 0
fi

# Update hosts file
PEER_COUNT=$(grep -cE '^[0-9]' "$TEMP_HOSTS" 2>/dev/null || echo "0")
# mktemp creates files mode 0600 by default. CoreDNS runs as a non-root UID
# inside its container and cannot read 0600 — hosts plugin loads zero records
# and every query falls through to the forward upstream, returning NODATA for
# every mesh service name. dnsmasq earlier worked because that container ran
# as root. See docs/findings/F-024-coredns-mesh-hosts-permission-blind-spot.md.
chmod 644 "$TEMP_HOSTS"
mv "$TEMP_HOSTS" "$HOSTS_FILE"
echo "$(date): Updated mesh-hosts ($PEER_COUNT peers)."

# Reload CoreDNS if on the router
if [ "$ON_ROUTER" = "true" ]; then
  cd "$DNS_DIR"
  docker compose restart coredns >/dev/null 2>&1 && echo "$(date): coredns reloaded." || echo "$(date): WARNING: Could not reload coredns."
fi
